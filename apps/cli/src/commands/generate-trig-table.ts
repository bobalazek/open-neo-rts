// bun neo generate-trig-table: writes packages/deterministic/src/trig/table.ts, the sine and CORDIC tables.
// Run once, offline. It uses Math.sin and Math.atan, which differ between engines, so its output is committed, never regenerated in CI.

import { writeFileSync } from "node:fs";

const FILE = "packages/deterministic/src/trig/table.ts";
const QUARTER = 16384; // binary angle units in a quarter turn
const ONE = 16384; // 2^14 = 1.0
const DIGITS_PER_ROW = 64;
const CORDIC_STEPS = 16; // max error under 1 binary angle unit; 14 steps reach 1.8

export async function generateTrigTable(): Promise<number> {
  let deltas = "";
  let previous = 0;
  for (let i = 1; i <= QUARTER; i++) {
    const value = Math.round(Math.sin((i * Math.PI) / (2 * QUARTER)) * ONE);
    deltas += value - previous; // sin rises at most pi/2 per unit, so every delta is 0, 1 or 2
    previous = value;
  }
  const rows: string[] = [];
  for (let i = 0; i < deltas.length; i += DIGITS_PER_ROW)
    rows.push(`  "${deltas.slice(i, i + DIGITS_PER_ROW)}",`);

  // atan(2^-i) in 1/256 binary angle units: 65,536 units = 2 pi radians.
  const steps = Array.from({ length: CORDIC_STEPS }, (_, i) =>
    Math.round((Math.atan(2 ** -i) * 2 ** 23) / Math.PI),
  );
  const stepLines: string[] = []; // packed to 100 columns, as Biome formats number arrays
  let line = " ";
  for (const step of steps) {
    if (line.length + ` ${step},`.length > 100) {
      stepLines.push(line);
      line = " ";
    }
    line += ` ${step},`;
  }
  stepLines.push(line);

  const text = [
    "// Generated by `bun neo generate-trig-table` with Math.sin and Math.atan, once, offline. Do not edit.",
    "// Committed so no engine computes trig at runtime (docs/engineering/numerics.md).",
    "",
    `/** sin over a quarter turn, scaled by 2^14, delta-encoded: digit i is entry i + 1 minus entry i, from entry 0 = 0. ${DIGITS_PER_ROW} per row. */`,
    "export const SIN_DELTAS: readonly string[] = [",
    ...rows,
    "];",
    "",
    "/** atan(2^-i) for CORDIC step i, in 1/256 binary angle units. */",
    "export const ATAN_STEPS: readonly number[] = [",
    ...stepLines,
    "];",
    "",
  ].join("\n");
  writeFileSync(FILE, text);
  console.log(`wrote ${QUARTER + 1} sine entries and ${CORDIC_STEPS} CORDIC steps to ${FILE}`);
  return 0;
}
